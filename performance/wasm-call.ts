type Api = {
  add(a: number, b: number): number;
  addf(a: number, b: number): number;
  load(at: number): number;
  bump(): number;
};

async function main(): Promise<void> {
  const imports = {
    env: {
      log: (_x: number) => {},
      fail: () => {},
      twice: (x: number) => x * 2
    }
  };
  const { instance } = await WebAssembly.instantiate(wasm, imports);
  const api = instance.exports as unknown as Api;
  const memory = instance.exports.memory as WebAssembly.Memory;
  const bytes = new Uint8Array(memory.buffer);
  for (let i = 0; i < 4096; i++) bytes[i] = (i * 31) & 255;

  const start = performance.now();
  let total = 0;
  for (let i = 0; i < 5_000_000; i++) {
    total += api.add(i & 1023, 7) & 255;
    total += api.addf(0.5, i & 3);
    total += api.load(i & 4095);
    if ((i & 255) === 0) total += api.bump() & 1;
  }
  const elapsed = performance.now() - start;
  console.log(`checksum: ${total}`);
  console.log(`elapsed: ${elapsed.toFixed(2)} ms`);
}

main();
