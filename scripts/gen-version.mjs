// Writes src/version.ts from package.json so the compiler can embed its own
// version (e.g. in scaffolded projects) without reading package.json at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const { version } = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf-8'));

writeFileSync(
  path.join(root, 'src', 'version.ts'),
  `// Generated by scripts/gen-version.mjs — do not edit.\nexport const VERSION = '${version}';\n`
);
