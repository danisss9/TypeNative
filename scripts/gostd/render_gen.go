package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// Render src/go/stdlib.generated.ts: one compact line-encoded string per
// package path. Line kinds:
//
//	P<name>            package name
//	F<name>|<tparams>|<params>|<results>|<variadic>
//	T<name>|<kind>|<under>|<tparams>|<numeric>
//	f<type>|<field>|<goTy>
//	M<type>|<method>|<ptr>|<params>|<results>
//	C<name>|<kind>|<goTy>
//	V<name>|<goTy>
//
// Params are comma-separated "name goTy" pairs (variadic keeps its "..."
// prefix). Results are comma-separated Go types. Parsed only for imported
// packages, so the self-hosted build stays fast.

func esc(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "\n", "\\n")
	s = strings.ReplaceAll(s, "|", "\\p")
	return s
}

func renderGenTS(models []pkgModel) string {
	var b strings.Builder
	b.WriteString("// Generated by `npm run gen:go`; do not edit.\n")
	b.WriteString("// Compact bridge metadata for every Go standard-library package.\n")
	b.WriteString("// Parsed on demand (only for imported packages) by src/go/metadata.ts.\n")
	b.WriteString("export const goStdlib: Record<string, string> = {\n")
	paths := make([]string, len(models))
	for i, m := range models {
		paths[i] = m.path
	}
	sort.Strings(paths)
	byPath := map[string]*pkgModel{}
	for i := range models {
		byPath[models[i].path] = &models[i]
	}
	for _, p := range paths {
		m := byPath[p]
		var lines []string
		lines = append(lines, "P"+esc(m.name))
		for _, fn := range m.funcs {
			var ps []string
			for _, pr := range fn.params {
				ps = append(ps, esc(pr.name)+" "+esc(pr.typ))
			}
			lines = append(lines, "F"+esc(fn.name)+"|"+esc(strings.Join(fn.tparams, ","))+"|"+
				strings.Join(ps, ",")+"|"+esc(strings.Join(fn.results, ","))+"|"+esc(strconv.FormatBool(fn.variadic)))
		}
		for _, ti := range m.typs {
			lines = append(lines, "T"+esc(ti.name)+"|"+esc(ti.kind)+"|"+esc(ti.under)+"|"+
				esc(strings.Join(ti.tparams, ","))+"|"+esc(strconv.FormatBool(ti.numeric)))
			for _, f := range ti.fields {
				lines = append(lines, "f"+esc(ti.name)+"|"+esc(f.name)+"|"+esc(f.goTy))
			}
			for _, mt := range ti.methods {
				var ps []string
				for _, pr := range mt.params {
					ps = append(ps, esc(pr.name)+" "+esc(pr.typ))
				}
				lines = append(lines, "M"+esc(ti.name)+"|"+esc(mt.name)+"|"+esc(strconv.FormatBool(mt.ptr))+"|"+
					strings.Join(ps, ",")+"|"+esc(strings.Join(mt.results, ",")))
			}
			for _, mt := range ti.ifaceMethods {
				var ps []string
				for _, pr := range mt.params {
					ps = append(ps, esc(pr.name)+" "+esc(pr.typ))
				}
				lines = append(lines, "I"+esc(ti.name)+"|"+esc(mt.name)+"|"+strings.Join(ps, ",")+"|"+esc(strings.Join(mt.results, ",")))
			}
		}
		for _, c := range m.consts {
			lines = append(lines, "C"+esc(c.name)+"|"+esc(c.kind)+"|"+esc(c.goTy))
		}
		for _, v := range m.vars {
			lines = append(lines, "V"+esc(v.name)+"|"+esc(v.goTy))
		}
		fmt.Fprintf(&b, "  %q: %q,\n", p, strings.Join(lines, "\n"))
	}
	b.WriteString("};\n")
	return b.String()
}
