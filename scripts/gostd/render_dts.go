package main

import (
	"fmt"
	"sort"
	"strings"
)

// Render types/typenative-go.d.ts: one `declare module 'go:<path>'` per
// package, plus the shared `go:builtin` module.

// Whether a Go type name is exported (usable from TypeScript declarations).
func isExportedName(name string) bool {
	if name == "" {
		return false
	}
	c := name[0]
	return c >= 'A' && c <= 'Z'
}

func renderDTS(models []pkgModel) string {
	all := map[string]*pkgModel{}
	for i := range models {
		all[models[i].path] = &models[i]
	}
	var b strings.Builder
	b.WriteString("// Generated by `npm run gen:go`; do not edit.\n")
	b.WriteString("// Go standard-library bridges: one module per package.\n")
	b.WriteString("// Numbers map to `number` (int64/uint64 beyond 2^53 lose precision).\n")
	b.WriteString("// `(T, error)` results throw; error-only calls throw as statements and\n")
	b.WriteString("// yield the error value otherwise.\n\n")
	b.WriteString(renderBuiltin())
	for _, m := range models {
		b.WriteString(renderModule(&m, all))
	}
	return b.String()
}

func renderBuiltin() string {	return `declare module 'go:builtin' {
  // A Go error value. Functions returning (T, error) throw a GoError instead.
  class GoError {
    message: string;
    Error(): string;
  }
  // A Go channel value.
  interface GoChan<T> {
    recv(): T;
    send(v: T): void;
    close(): void;
    [Symbol.iterator](): IterableIterator<T>;
  }
  function chan<T>(size?: number): GoChan<T>;
  // A pointer cell for out-params (json.Unmarshal, flag.StringVar, ...).
  interface GoRef<T> {
    value: T;
  }
  function ref<T>(init?: T): GoRef<T>;
}
`
}

func renderModule(m *pkgModel, all map[string]*pkgModel) string {
	tm := newTypeMapper(m, all)
	var b strings.Builder
	fmt.Fprintf(&b, "\ndeclare module 'go:%s' {\n", m.path)
	// Named numeric types first (type + conversion function).
	for _, ti := range m.typs {
		if ti.kind == "basic" && ti.numeric && isExportedName(ti.name) {
			writeNumeric(&b, &ti, tm)
		}
	}
	// Other types (unexported helper types stay metadata-only).
	for _, ti := range m.typs {
		if ti.kind == "basic" && ti.numeric {
			continue
		}
		if !isExportedName(ti.name) {
			continue
		}
		writeType(&b, &ti, tm)
	}
	// Functions.
	for _, fn := range m.funcs {
		writeFunc(&b, &fn, tm)
	}
	// Consts.
	for _, c := range m.consts {
		writeConst(&b, &c, tm, m)
	}
	// Vars.
	for _, v := range m.vars {
		fmt.Fprintf(&b, "  export const %s: %s;\n", sanitizeName(v.name), tm.mapType(v.goTy, "field"))
	}
	b.WriteString("}\n")
	return b.String()
}

func writeNumeric(b *strings.Builder, ti *typeInfo, tm *typeMapper) {
	var methods []string
	for _, mt := range ti.methods {
		methods = append(methods, "    "+renderMethodSig(mt.name, mt.params, mt.results, nil, tm)+";")
	}
	if len(methods) == 0 {
		fmt.Fprintf(b, "  export type %s = number;\n", sanitizeName(ti.name))
	} else {
		fmt.Fprintf(b, "  export type %s = number & {\n%s\n  };\n", sanitizeName(ti.name), strings.Join(methods, "\n"))
	}
	fmt.Fprintf(b, "  export function %s(v: number): %s;\n", sanitizeName(ti.name), sanitizeName(ti.name))
}

func writeType(b *strings.Builder, ti *typeInfo, tm *typeMapper) {
	tparams := ""
	if len(ti.tparams) > 0 {
		tparams = "<" + strings.Join(ti.tparams, ", ") + ">"
	}
	name := sanitizeName(ti.name)
	switch ti.kind {
	case "alias":
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "basic":
		// Non-numeric basics (string, bool).
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "func":
		// iter.Seq / Seq2 are also for…of iterables.
		iterable := ""
		if tm.path == "iter" && name == "Seq" {
			iterable = " & Iterable<V>"
		} else if tm.path == "iter" && name == "Seq2" {
			iterable = " & Iterable<[K, V]>"
		}
		fmt.Fprintf(b, "  export type %s%s = (%s)%s;\n", name, tparams, tm.mapType(ti.under, "result"), iterable)
	case "slice":
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "map":
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "array":
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "chan":
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "other":
		fmt.Fprintf(b, "  export type %s%s = %s;\n", name, tparams, tm.mapType(ti.under, "result"))
	case "interface":
		fmt.Fprintf(b, "  export interface %s%s {\n", name, tparams)
		for _, mt := range ti.ifaceMethods {
			fmt.Fprintf(b, "    %s;\n", renderMethodSig(mt.name, mt.params, mt.results, nil, tm))
		}
		b.WriteString("  }\n")
	case "struct":
		fmt.Fprintf(b, "  export class %s%s {\n", name, tparams)
		fmt.Fprintf(b, "    constructor(init?: Partial<%s%s>);\n", name, tparams)
		for _, f := range ti.fields {
			fmt.Fprintf(b, "    %s: %s;\n", sanitizeName(f.name), tm.mapType(f.goTy, "field"))
		}
		for _, mt := range ti.methods {
			fmt.Fprintf(b, "    %s;\n", renderMethodSig(mt.name, mt.params, mt.results, nil, tm))
		}
		b.WriteString("  }\n")
	}
}

func renderMethodSig(name string, params []paramInfo, results []string, tparams []string, tm *typeMapper) string {
	return renderSigs(sanitizeName(name), params, results, tparams, tm, ";\n    ")
}

// One signature, plus an overload taking the variadic slot as a slice.
func renderSigs(name string, params []paramInfo, results []string, tparams []string, tm *typeMapper, sep string) string {
	tp := ""
	if len(tparams) > 0 {
		tp = "<" + strings.Join(tparams, ", ") + ">"
	}
	ret := tm.mapResults(results)
	sig := fmt.Sprintf("%s%s(%s): %s", name, tp, tm.renderParams(params, false), ret)
	if hasVariadic(params) {
		sig += sep + fmt.Sprintf("%s%s(%s): %s", name, tp, tm.renderParams(params, true), ret)
	}
	return sig
}

func writeFunc(b *strings.Builder, fn *funcInfo, tm *typeMapper) {
	params, results, tparams := inlineCoreTypes(fn)
	fmt.Fprintf(b, "  export function %s;\n", renderSigs(sanitizeName(fn.name), params, results, tparams, tm, ";\n  export function "))
}

// Type params with a core type (Slice ~[]E, Map ~map[K]V) are replaced by
// it, so TypeScript can infer the rest: Clone<S ~[]E, E>(s S) S renders as
// Clone<E>(s: E[]): E[].
func inlineCoreTypes(fn *funcInfo) ([]paramInfo, []string, []string) {
	subst := map[string]string{}
	for i, tp := range fn.tparams {
		if i < len(fn.tcores) && fn.tcores[i] != "" {
			subst[tp] = fn.tcores[i]
		}
	}
	if len(subst) == 0 {
		return fn.params, fn.results, fn.tparams
	}
	var tparams []string
	for _, tp := range fn.tparams {
		if _, ok := subst[tp]; !ok {
			tparams = append(tparams, tp)
		}
	}
	params := make([]paramInfo, len(fn.params))
	for i, p := range fn.params {
		params[i] = paramInfo{name: p.name, typ: substituteTypeParams(p.typ, subst)}
	}
	results := make([]string, len(fn.results))
	for i, r := range fn.results {
		results[i] = substituteTypeParams(r, subst)
	}
	return params, results, tparams
}

// Replace type-param identifiers (not selector or path parts) in a Go type.
// Cores may name other params with cores, so substitute to a fixed point.
func substituteTypeParams(goTy string, subst map[string]string) string {
	for depth := 0; depth < 4; depth++ {
		var b strings.Builder
		changed := false
		for i := 0; i < len(goTy); {
			c := goTy[i]
			if c == '_' || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') {
				j := i + 1
				for j < len(goTy) && (goTy[j] == '_' || (goTy[j] >= 'A' && goTy[j] <= 'Z') || (goTy[j] >= 'a' && goTy[j] <= 'z') || (goTy[j] >= '0' && goTy[j] <= '9')) {
					j++
				}
				word := goTy[i:j]
				selector := i > 0 && (goTy[i-1] == '/' || (goTy[i-1] == '.' && !strings.HasSuffix(goTy[:i], "...")))
				if r, ok := subst[word]; ok && !selector {
					b.WriteString(r)
					changed = true
				} else {
					b.WriteString(word)
				}
				i = j
				continue
			}
			b.WriteByte(c)
			i++
		}
		goTy = b.String()
		if !changed {
			break
		}
	}
	return goTy
}

func writeConst(b *strings.Builder, c *constInfo, tm *typeMapper, m *pkgModel) {	switch c.kind {
	case "string":
		fmt.Fprintf(b, "  export const %s: string;\n", sanitizeName(c.name))
	case "bool":
		fmt.Fprintf(b, "  export const %s: boolean;\n", sanitizeName(c.name))
	case "typed":
		// Named-type constant: keeps its type (and methods), since the
		// bridge reads it without converting (crypto.SHA256.Size()).
		ts := tm.mapType(c.goTy, "result")
		if qpath, name := splitQual(c.goTy); qpath == "" || qpath == tm.path {
			if _, ok := tm.numerics[name]; ok {
				ts = sanitizeName(name)
			}
		}
		fmt.Fprintf(b, "  export const %s: %s;\n", sanitizeName(c.name), ts)
	default:
		fmt.Fprintf(b, "  export const %s: number;\n", sanitizeName(c.name))
	}
	_ = tm
	_ = m
	_ = sort.Strings
}
