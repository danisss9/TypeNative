const mem = new WebAssembly.Memory({ initial: 1, maximum: 2 });
assert(mem.buffer.byteLength === 65536, 'a new Memory');
new Uint8Array(mem.buffer)[3] = 40;
const base = new WebAssembly.Global({ value: 'i32', mutable: false }, 100);
assert(base.value === 100 && base.valueOf() === 100, 'a new Global');
const big = new WebAssembly.Global({ value: 'i64', mutable: true }, 5n);
big.value = -7n;
assert(big.value === -7n, 'an i64 Global holds a bigint');

const linkModule = new WebAssembly.Module(linkWasm);
const a = new WebAssembly.Instance(linkModule, { env: { mem, base, inc: (x: number) => x + 1 } });
const readA = a.exports.read as (at: number) => number;
assert(readA(3) === 141, 'a JS Memory / Global / function');
new Uint8Array(mem.buffer)[3] = 50;
assert(readA(3) === 151, 'the memory is shared, not copied');

// another instance's exports as imports: its memory and its function
const basic = new WebAssembly.Instance(new WebAssembly.Module(basicWasm), {
  env: { log: (_x: number) => {}, fail: () => {}, twice: (x: number) => x * 2 }
});
const add = basic.exports.add as (a: number, b: number) => number;
const b = new WebAssembly.Instance(linkModule, {
  env: { mem: basic.exports.memory, base: 1000, inc: (x: number) => add(x, 3) }
});
const readB = b.exports.read as (at: number) => number;
assert(readB(16) === 0x68 + 3 + 1000, 'an exported memory, an exported function and a number');
new Uint8Array((basic.exports.memory as WebAssembly.Memory).buffer)[16] = 1;
assert(readB(16) === 1004, 'both instances see one memory');

let linkError = false;
try {
  new WebAssembly.Instance(linkModule, { env: { mem: 1, base, inc: (x: number) => x } });
} catch (e) {
  linkError = e instanceof WebAssembly.LinkError;
}
assert(linkError, 'a memory import needs a Memory');

