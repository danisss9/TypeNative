// node:test snapshots: t.assert.snapshot (one entry per assertion, Node's
// <test file>.snapshot format) and t.assert.fileSnapshot, written by
// --test-update-snapshots and compared otherwise; a missing file names the
// flag. The probe runs itself as a child in each mode, with the snapshot
// files redirected to a temp dir (snapshot.setResolveSnapshotPath).
import { spawnSync } from 'node:child_process';
import { test, snapshot } from 'node:test';
import assert from 'node:assert';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// unset env vars read as '' (use ||, not ??)
const dir = process.env.TN_SNAP_DIR || mkdtempSync(path.join(os.tmpdir(), 'tn-snap-'));
snapshot.setResolveSnapshotPath(() => path.join(dir, 'probe.snapshot'));

if (process.env.TN_SNAP_CHILD) {
  const second = process.env.TN_SNAP_SECOND || 'second';
  test('snap values', (t) => {
    t.assert.snapshot({ b: 2, a: 1 });
    t.assert.snapshot(second);
  });
  test('suite > sub', async (t) => {
    await t.test('child', (t) => {
      t.assert.snapshot([1, 2]);
    });
  });
  test('file snapshot', (t) => {
    t.assert.fileSnapshot({ answer: 42 }, path.join(dir, 'answer.json'));
  });
} else {
  const run = (options: string, second: string): { out: string; status: number | null } => {
    process.env.TN_SNAP_SECOND = second;
    const child = spawnSync(process.execPath, [...process.execArgv, ...process.argv.slice(1)], {
      env: { ...process.env, TN_SNAP_CHILD: '1', TN_SNAP_DIR: dir, NODE_OPTIONS: options },
      encoding: 'utf8'
    });
    return { out: child.stdout ?? '', status: child.status };
  };

  // no snapshot file yet: each snapshot test fails, naming the flag
  const missing = run('--test-reporter=tap', 'second');
  assert(missing.status === 1, `missing snapshots fail: ${missing.status}`);
  assert(missing.out.includes('not ok 1 - snap values'), `missing fails the test: ${missing.out}`);
  assert(
    missing.out.includes('Cannot read snapshot file') &&
      missing.out.includes('Missing snapshots can be generated by rerunning the command with the --test-update-snapshots flag.'),
    `the missing-file error: ${missing.out}`
  );

  // --test-update-snapshots writes the file, entries sorted by name (a file
  // snapshot writes its own file, not an entry)
  const update = run('--test-update-snapshots --test-reporter=tap', 'second');
  assert(update.status === 0, `update passes: ${update.out}`);
  const expected = [
    'exports[`snap values 1`] = `\n{\n  "b": 2,\n  "a": 1\n}\n`;',
    'exports[`snap values 2`] = `\n"second"\n`;',
    'exports[`suite > sub > child 1`] = `\n[\n  1,\n  2\n]\n`;'
  ].join('\n\n') + '\n';
  assert(existsSync(path.join(dir, 'probe.snapshot')), 'the snapshot file exists');
  assert(readFileSync(path.join(dir, 'probe.snapshot'), 'utf8') === expected, `snapshot file format`);
  assert(readFileSync(path.join(dir, 'answer.json'), 'utf8') === '{\n  "answer": 42\n}', 'file snapshot content');

  // with the file in place the assertions pass
  const pass = run('--test-reporter=tap', 'second');
  assert(pass.status === 0, `snapshots pass: ${pass.out}`);

  // a changed value fails the comparison with Node's strictEqual diff
  const changed = run('--test-reporter=tap', 'changed');
  assert(changed.status === 1, `a changed value fails: ${changed.status}`);
  assert(changed.out.includes('not ok 1 - snap values'), `the changed value fails the test: ${changed.out}`);
  assert(
    changed.out.includes("Expected values to be strictly equal") && changed.out.includes('"changed"') && changed.out.includes('"second"'),
    `the comparison diff: ${changed.out}`
  );

  rmSync(dir, { recursive: true, force: true });
  assert(!existsSync(path.join(dir, 'probe.snapshot')), 'cleanup');
  console.log('test snapshots ok');
}
